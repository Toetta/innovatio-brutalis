test("All local links, images and fragments on indexable pages resolve", async () => {
  const problems = [];
  const fileCache = new Map();
  for (const route of expectedRoutes) {
    const html = await read(routeFile(route));
    for (const tag of [...tags(html, "a"), ...tags(html, "img"), ...tags(html, "source"), ...tags(html, "link"), ...tags(html, "script")]) {
      const reference = tag.href || tag.src || tag.srcset?.split(",")[0].trim().split(/\s/)[0];
      if (!reference || /^(mailto|tel|data|javascript):/.test(reference)) continue;
      const url = new URL(reference, origin + route);
      if (url.origin !== origin) continue;
      const targetPath = decodeURIComponent(url.pathname);
      const relative = targetPath.endsWith("/") ? targetPath.slice(1) + "index.html" : targetPath.slice(1);
      const target = path.join(root, ...relative.split("/"));
      try {
        await access(target);
        if (url.hash && relative.endsWith(".html")) {
          if (!fileCache.has(target)) fileCache.set(target, await readFile(target, "utf8"));
          const targetHtml = fileCache.get(target);
          const id = decodeURIComponent(url.hash.slice(1));
          if (!tags(targetHtml, "[a-z][a-z0-9-]*").some((element) => element.id === id || element.name === id)) problems.push(`${route}: missing fragment ${reference}`);
        }
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
        problems.push(`${route}: missing target ${reference}`);
      }
    }
  }
  assert.deepEqual(problems, []);
});

