import { readdir, readFile, writeFile, mkdir, unlink, rmdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { areaServed, cardsHtml, escapeHtml, origin, pageHtml, renderMarkdown } from "./seo-html.mjs";

export const root = fileURLToPath(new URL("..", import.meta.url));
const generatedMarker = "<!-- Generated by tools/build-seo.mjs.";
const excludedDirs = new Set([".git", ".github", ".githooks", ".local", ".wrangler", "node_modules", "assets", "content", "tools", "tmp", "external", "functions"]);

export const htmlFiles = async (dir = root) => {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory() && !excludedDirs.has(entry.name)) result.push(...await htmlFiles(file));
    else if (entry.isFile() && entry.name.endsWith(".html")) result.push(file);
  }
  return result.sort();
};

const loadEntries = async (kind) => {
  const dir = path.join(root, "content", kind);
  const entries = [];
  for (const filename of (await readdir(dir)).filter((name) => name.endsWith(".json")).sort()) {
    const source = path.join(dir, filename);
    const entry = JSON.parse(await readFile(source, "utf8"));
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.slug) || filename !== `${entry.slug}.json`) {
      throw new Error(`Slug must match filename: ${source}`);
    }
    if (typeof entry.published !== "boolean") throw new Error(`Missing published flag: ${source}`);
    if (!entry.published) continue;
    for (const key of ["title", "description", "body"]) {
      if (typeof entry[key] !== "string" || !entry[key].trim()) throw new Error(`Missing ${key}: ${source}`);
    }
    if (kind === "articles" && (!entry.date || !Number.isFinite(Date.parse(entry.date)))) {
      throw new Error(`Invalid article date: ${source}`);
    }
    entries.push({ ...entry, source });
  }
  return entries.sort((a, b) => String(b.date || "").localeCompare(String(a.date || "")) || a.slug.localeCompare(b.slug));
};

const writeIfChanged = async (file, content) => {
  let previous;
  try {
    previous = await readFile(file, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous !== content) await writeFile(file, content, "utf8");
};

const writePage = async (route, html) => {
  const file = path.join(root, ...route.split("/").filter(Boolean), "index.html");
  await mkdir(path.dirname(file), { recursive: true });
  await writeIfChanged(file, html);
  return file;
};

const lastModified = (files, modified) => {
  if (files.some((file) => modified.has(path.relative(root, file).split(path.sep).join("/")))) return "";
  // Git dates avoid changing lastmod just because a build re-created identical HTML.
  return execFileSync("git", ["--no-pager", "log", "-1", "--format=%cs", "--", ...files.map((file) => path.relative(root, file))], { cwd: root, encoding: "utf8" }).trim();
};

export const buildSeo = async () => {
  const sources = new Map();
  const generated = new Set();
  for (const kind of ["articles", "cases"]) {
    const routeKind = kind === "cases" ? "case" : "articles";
    const entries = await loadEntries(kind);
    for (const entry of entries) {
      const route = `/${routeKind}/${entry.slug}/`;
      const author = entry.author
        ? { "@type": "Person", name: entry.author }
        : { "@type": "Organization", "@id": `${origin}/#org`, name: "Innovatio Brutalis" };
      const schema = {
        "@context": "https://schema.org",
        "@type": kind === "articles" ? "BlogPosting" : "Article",
        headline: entry.title,
        description: entry.description,
        url: origin + route,
        mainEntityOfPage: { "@type": "WebPage", "@id": origin + route },
        inLanguage: "sv-SE",
        author,
        publisher: { "@id": `${origin}/#org`, "@type": "Organization", name: "Innovatio Brutalis", logo: { "@type": "ImageObject", url: `${origin}/assets/logo.png` } },
        image: new URL(entry.image || "/assets/og-image.jpg", origin).href,
        ...(entry.date ? { datePublished: entry.date } : {}),
        ...(entry.modified ? { dateModified: entry.modified } : {}),
      };
      const date = entry.date ? `<time datetime="${escapeHtml(entry.date)}">${escapeHtml(entry.date.slice(0, 10))}</time> · ` : "";
      const image = entry.image ? `<img src="${escapeHtml(entry.image)}" alt="${escapeHtml(entry.image_alt || entry.title)}" loading="lazy" decoding="async" style="width:100%;height:auto;border-radius:var(--radius);">` : "";
      const content = `<article class="card" style="margin-top:28px;">
  <p><a href="/${routeKind}/">${kind === "articles" ? "Alla artiklar" : "Alla case"}</a> · ${escapeHtml(entry.category || routeKind)}</p>
  <p>${date}${escapeHtml(entry.author || "Innovatio Brutalis")}</p>
  ${image}
  ${renderMarkdown(entry.body, entry.title)}
</article>`;
      const file = await writePage(route, pageHtml({ ...entry, route, kind: routeKind, heading: entry.title, title: `${entry.title} | Innovatio Brutalis` }, content, [schema]));
      generated.add(file);
      sources.set(file, [entry.source]);
    }
    const index = {
      route: `/${routeKind}/`,
      kind: routeKind,
      heading: kind === "articles" ? "Artiklar om produktutveckling och tillverkning" : "Case: från problem till fysisk lösning",
      title: kind === "articles" ? "Artiklar om prototyper & produktutveckling | Innovatio Brutalis" : "Case inom produktutveckling & prototyper | Innovatio Brutalis",
      description: kind === "articles" ? "Faktabaserade artiklar om prototypframtagning, reverse engineering, 3D-print och CNC med koppling till tjänster och projekt hos Innovatio Brutalis i Malmö." : "Dokumenterade projekt hos Innovatio Brutalis i Malmö: problem, CAD, materialval, prototyper, test och resultat.",
    };
    const content = `<section class="card" style="margin-top:28px;">
  <p><a href="/prototypframtagning/">Produktutveckling och prototypframtagning i Malmö</a> – bas i Malmö, för företag i Skåne och södra Sverige.</p>
  ${cardsHtml(entries.filter((entry) => entry.indexable !== false), routeKind)}
</section>`;
    const file = await writePage(index.route, pageHtml(index, content));
    sources.set(file, entries.map((entry) => entry.source));
    generated.add(file);
  }

  const pagesDir = path.join(root, "content", "pages");
  for (const filename of (await readdir(pagesDir)).filter((name) => name.endsWith(".json")).sort()) {
    const source = path.join(pagesDir, filename);
    const page = JSON.parse(await readFile(source, "utf8"));
    if (!/^\/(?:[a-z0-9-]+\/)+$/.test(page.route)) throw new Error(`Invalid page route: ${source}`);
    const schemas = [{
      "@context": "https://schema.org",
      "@type": "Service",
      name: page.service.name,
      serviceType: page.service.types,
      provider: { "@type": "ProfessionalService", "@id": `${origin}/#org`, name: "Innovatio Brutalis", url: origin + "/", address: { "@type": "PostalAddress", addressLocality: "Malmö", addressRegion: "Skåne", addressCountry: "SE" } },
      areaServed,
      url: origin + page.route,
      description: page.description,
    }];
    let faq = "";
    if (page.faq?.length) {
      schemas.push({
        "@context": "https://schema.org",
        "@type": "FAQPage",
        mainEntity: page.faq.map(({ question, answer }) => ({
          "@type": "Question", name: question, acceptedAnswer: { "@type": "Answer", text: answer },
        })),
      });
      faq = `<section class="card" style="margin-top:28px;">
  <h2>${page.lang === "en" ? "Questions about prototyping" : "Frågor om prototypframtagning"}</h2>
  ${page.faq.map(({ question, answer }) => `<h3>${escapeHtml(question)}</h3><p>${escapeHtml(answer)}</p>`).join("\n  ")}
</section>`;
    }
    const content = `<div class="cta-row">
  <a class="btn" href="#${page.lang === "en" ? "contact" : "kontakt"}" data-ga-event="quote_request">${page.lang === "en" ? "Discuss your idea or part" : "Diskutera din idé eller detalj"}</a>
</div>
<section class="card" style="margin-top:28px;">${renderMarkdown(page.body)}</section>
${page.project_links?.length ? `<section class="card" style="margin-top:28px;">
  <h2>${page.lang === "en" ? "More documented projects" : "Fler dokumenterade projekt"}</h2>
  ${renderMarkdown(page.project_links.map(({ href, label }) => `- [${label}](${href})`).join("\n"))}
</section>` : ""}
${faq}`;
    const file = await writePage(page.route, pageHtml(page, content, schemas));
    sources.set(file, [source]);
    generated.add(file);
  }

  // Remove only marked generated files when a source is unpublished, renamed or deleted.
  for (const file of await htmlFiles()) {
    const html = await readFile(file, "utf8");
    if (!html.includes(generatedMarker) || generated.has(file)) continue;
    await unlink(file);
    if ((await readdir(path.dirname(file))).length === 0) await rmdir(path.dirname(file));
  }

  const urls = new Map();
  const modified = new Set(execFileSync("git", ["diff", "--name-only", "HEAD"], { cwd: root, encoding: "utf8" }).trim().split("\n"));
  for (const file of await htmlFiles()) {
    const html = await readFile(file, "utf8");
    if (/<meta\b[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html)) continue;
    const canonical = html.match(/<link\b[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["']/i)?.[1];
    if (!canonical) continue;
    const url = new URL(canonical);
    if (url.origin !== origin) throw new Error(`Unexpected canonical host in ${file}`);
    const expected = path.relative(root, file).split(path.sep).join("/").replace(/index\.html$/, "");
    if (url.pathname !== "/" + expected || url.search || url.hash) throw new Error(`Canonical does not match file: ${file}`);
    if (urls.has(canonical)) throw new Error(`Duplicate canonical: ${canonical}`);
    urls.set(canonical, lastModified([file, ...(sources.get(file) || [])], modified));
  }
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[...urls].sort(([a], [b]) => a.localeCompare(b)).map(([url, date]) => `  <url><loc>${escapeHtml(url)}</loc>${date ? `<lastmod>${date}</lastmod>` : ""}</url>`).join("\n")}
</urlset>
`;
  await writeIfChanged(path.join(root, "sitemap.xml"), sitemap);
  console.log(`SEO built: ${generated.size} static pages, ${urls.size} sitemap URLs`);
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildSeo().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
